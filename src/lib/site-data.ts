type DoorStyle = keyof typeof doorStyles;

// Generated by `npm run photos` from the files in photo-originals/door-models/.
const models = doorModels as { id: string; style: DoorStyle; number: number; veneer: boolean }[];

export const doorFamilies: DoorFamily[] = (Object.keys(doorStyles) as DoorStyle[]).map((style) => ({
  slug: doorStyles[style].slug,
  name: doorStyles[style].name,
  intro: doorStyles[style].intro,
  title: `${doorStyles[style].name} durys`,
  description: placeholderDoorDescription,
  patterns: models
    .filter((m) => m.style === style)
    .sort((a, b) => a.number - b.number)
    .map((m) => ({
      number: m.number,
      image: `/images/durys/${m.id}-sm.webp`,
      imageLarge: `/images/durys/${m.id}-lg.webp`,
      ...(m.veneer ? { veneerImage: `/images/durys/${m.id}-fanier-lg.webp` } : {}),
    })),
}));

